-- 추천 카드 응답(A_SPEC §8 [제안]·§14). 사용자·카드 메시지당 1행 — 최초 응답을 고정한다.
-- 응답은 점수·단계·추천을 바꾸지 않는다. created_at은 애플리케이션 Clock 값.
CREATE TABLE recommendation_responses (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT                   NOT NULL,
    message_id BIGINT                   NOT NULL,
    routine_id VARCHAR(40)              NOT NULL,
    response   VARCHAR(20)              NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_recommendation_responses_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_recommendation_responses_message FOREIGN KEY (message_id) REFERENCES chat_messages (id),
    CONSTRAINT uk_recommendation_responses_user_message UNIQUE (user_id, message_id),
    CONSTRAINT ck_recommendation_responses_response CHECK (response IN ('ACCEPTED', 'DECLINED'))
);
