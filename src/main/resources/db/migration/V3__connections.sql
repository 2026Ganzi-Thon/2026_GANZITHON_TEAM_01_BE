-- 연동 소스별 연결 상태(사용자·소스당 1행). 동의 이력은 user_consents(consent_type=DATA_SOURCE)에 따로 쌓는다.
-- 이력이 없는 소스는 행이 없다(API에서는 NOT_CONNECTED). MVP의 provider는 DEMO뿐이다(ADR-006).
-- connected_at·revoked_at은 애플리케이션 Clock 값이므로 DEFAULT를 두지 않는다.
CREATE TABLE connections (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT                   NOT NULL,
    source       VARCHAR(40)              NOT NULL,
    provider     VARCHAR(20)              NOT NULL,
    status       VARCHAR(20)              NOT NULL,
    connected_at TIMESTAMP WITH TIME ZONE NULL,
    revoked_at   TIMESTAMP WITH TIME ZONE NULL,
    CONSTRAINT fk_connections_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uk_connections_user_source UNIQUE (user_id, source),
    CONSTRAINT ck_connections_status CHECK (status IN ('CONNECTED', 'REVOKED'))
);
