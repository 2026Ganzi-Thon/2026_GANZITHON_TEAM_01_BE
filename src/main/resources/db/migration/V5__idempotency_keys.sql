-- 재시도 중복 방지(A_SPEC §13 Idempotency-Key, §14). 같은 (user_id, endpoint, idem_key)는 한 번만 처리한다.
-- request_hash: 요청 본문 JSON의 SHA-256(hex). 같은 키로 다른 요청이 오면 409.
-- response_body는 재생용이며 로그에 남기지 않는다. created_at은 애플리케이션 Clock 값(DEFAULT 없음).
CREATE TABLE idempotency_keys (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT                   NOT NULL,
    endpoint        VARCHAR(100)             NOT NULL,
    idem_key        VARCHAR(64)              NOT NULL,
    request_hash    VARCHAR(64)              NOT NULL,
    response_status INT                      NOT NULL,
    response_body   TEXT                     NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_idempotency_keys_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uk_idempotency_keys UNIQUE (user_id, endpoint, idem_key)
);
