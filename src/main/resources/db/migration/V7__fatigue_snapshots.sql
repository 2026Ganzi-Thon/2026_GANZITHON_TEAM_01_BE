-- 사용자·날짜별 피로 계산 결과(engine 결과 스냅샷, A_SPEC §12·§14). 값은 engine 결과를 그대로 저장한다.
-- 근거가 없으면 status=INSUFFICIENT_DATA이고 score·level·wool_display_kg는 NULL이다(0·1단계로 채우지 않는다).
-- engine 실패 시 마지막 정상 값을 두고 is_stale=TRUE로 표시한다. used_sources는 JSON 문자열(ADR-004).
-- calculated_at은 engine이 준 값, updated_at은 애플리케이션 Clock 값(DEFAULT 없음).
CREATE TABLE fatigue_snapshots (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT                   NOT NULL,
    local_date        DATE                     NOT NULL,
    score             INT                      NULL,
    level             SMALLINT                 NULL,
    wool_display_kg   NUMERIC(4, 2)            NULL,
    status            VARCHAR(30)              NOT NULL,
    status_text       VARCHAR(100)             NULL,
    sub_text          VARCHAR(200)             NULL,
    asset_key         VARCHAR(100)             NULL,
    algorithm_version VARCHAR(50)              NOT NULL,
    used_sources      TEXT                     NOT NULL,
    is_stale          BOOLEAN                  NOT NULL,
    calculated_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_fatigue_snapshots_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uk_fatigue_snapshots_user_date UNIQUE (user_id, local_date),
    CONSTRAINT ck_fatigue_snapshots_level CHECK (level BETWEEN 1 AND 4),
    CONSTRAINT ck_fatigue_snapshots_score CHECK (score BETWEEN 0 AND 100),
    CONSTRAINT ck_fatigue_snapshots_status CHECK (status IN ('CALCULATED', 'INSUFFICIENT_DATA'))
);
