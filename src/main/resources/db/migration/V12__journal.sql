-- 마음 정리 기록과 털 깎임 연출 이벤트(A_SPEC §9·§14).
-- journal_entries.text는 원문 그대로 저장한다(HTML 이스케이프 없음 — 화면은 텍스트로 출력해야 한다).
-- 이 기록은 engine에 넘기지 않는다. 털 깎임은 연출 값일 뿐 피로 점수·단계를 바꾸지 않는다.
-- wool_trim_events: 사용자·날짜·출처당 1행(하루 한 번 연출). visual_value 형식은 B 합의 대기(현재 NULL).
CREATE TABLE journal_entries (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT                   NOT NULL,
    local_date DATE                     NOT NULL,
    emotion    VARCHAR(20)              NULL,
    text       TEXT                     NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_journal_entries_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_journal_entries_emotion
        CHECK (emotion IN ('ANXIOUS', 'FRUSTRATED', 'TIRED', 'LETHARGIC', 'OKAY'))
);

CREATE INDEX idx_journal_entries_user_date ON journal_entries (user_id, local_date);

CREATE TABLE wool_trim_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT                   NOT NULL,
    local_date   DATE                     NOT NULL,
    source       VARCHAR(20)              NOT NULL,
    visual_value VARCHAR(100)             NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_wool_trim_events_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uk_wool_trim_events_user_date_source UNIQUE (user_id, local_date, source),
    CONSTRAINT ck_wool_trim_events_source CHECK (source IN ('JOURNAL'))
);
