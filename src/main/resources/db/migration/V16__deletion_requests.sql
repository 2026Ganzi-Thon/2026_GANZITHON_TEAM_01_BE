-- 삭제·탈퇴 처리 기록(A_SPEC §14). 탈퇴 후에도 남으므로 user_id를 두지 않는다(익명화).
-- subject_hash = subjectKey의 SHA-256(hex): 같은 사용자의 기록 삭제 상태를 조회할 때만 쓴다.
-- status: DB 삭제와 engine 처리물 삭제가 모두 끝나면 COMPLETED, engine 삭제가 실패하면 ENGINE_PENDING.
CREATE TABLE deletion_requests (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_hash VARCHAR(64)              NOT NULL,
    scope        VARCHAR(10)              NOT NULL,
    status       VARCHAR(20)              NOT NULL,
    requested_at TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE NULL,
    CONSTRAINT ck_deletion_requests_scope CHECK (scope IN ('DATA', 'ACCOUNT')),
    CONSTRAINT ck_deletion_requests_status CHECK (status IN ('COMPLETED', 'ENGINE_PENDING'))
);

CREATE INDEX idx_deletion_requests_subject ON deletion_requests (subject_hash, requested_at);
