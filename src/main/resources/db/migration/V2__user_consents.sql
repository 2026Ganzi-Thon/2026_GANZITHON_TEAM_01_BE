-- 동의 이력. 변경할 때마다 새 행을 INSERT하고 UPDATE·DELETE하지 않는다(명세 §3 이력 누적).
-- 현재 상태 = (user_id, consent_type, source)별 가장 최근 changed_at 행(같으면 id가 큰 행).
-- source는 DATA_SOURCE(선택 연동 동의)일 때만 쓴다. items는 문자열 JSON 배열(ADR-004).
-- policy_version은 서버 설정값, changed_at은 애플리케이션 Clock 값이므로 DEFAULT를 두지 않는다.
CREATE TABLE user_consents (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT                   NOT NULL,
    consent_type   VARCHAR(40)              NOT NULL,
    source         VARCHAR(40)              NULL,
    items          VARCHAR(1000)            NULL,
    purpose        VARCHAR(500)             NULL,
    retention      VARCHAR(200)             NULL,
    is_granted     BOOLEAN                  NOT NULL,
    policy_version VARCHAR(40)              NOT NULL,
    changed_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_user_consents_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX ix_user_consents_user_type_source_changed
    ON user_consents (user_id, consent_type, source, changed_at);
