-- 대화 메시지(A_SPEC §8·§14). 스레드 = 사용자별 하루(thread_date, KST).
-- content는 원문이다(로그 금지). payload는 카드 정보 JSON 문자열(ADR-004).
-- is_greeting: 하루 1회 선제 인사(사용자·날짜당 최대 1개, 부분 유니크).
CREATE TABLE chat_messages (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT                   NOT NULL,
    thread_date  DATE                     NOT NULL,
    role         VARCHAR(10)              NOT NULL,
    message_type VARCHAR(30)              NOT NULL,
    content      TEXT                     NOT NULL,
    payload      TEXT                     NULL,
    risk_flag    BOOLEAN                  NOT NULL,
    is_greeting  BOOLEAN                  NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_chat_messages_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_chat_messages_role CHECK (role IN ('USER', 'SOMI')),
    CONSTRAINT ck_chat_messages_type CHECK (message_type IN ('TEXT', 'WEEK_SUMMARY', 'ROUTINE_RECOMMENDATION'))
);

CREATE INDEX idx_chat_messages_user_thread ON chat_messages (user_id, thread_date, created_at);
CREATE UNIQUE INDEX uk_chat_messages_greeting ON chat_messages (user_id, thread_date) WHERE is_greeting;
