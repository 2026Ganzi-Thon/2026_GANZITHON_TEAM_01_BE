-- 하루 체크인(A_SPEC §6). 사용자·날짜(KST, 서버 산출)당 1행이며 재제출은 같은 행을 갱신한다.
-- '다음에 하기'로 넘긴 문항은 NULL. '기타'(OTHER)는 선택지일 뿐 자유 입력 컬럼은 없다.
-- status: 세 문항이 모두 비면 SKIPPED, 하나라도 있으면 SUBMITTED.
-- created_at·updated_at은 애플리케이션 Clock 값이므로 DEFAULT를 두지 않는다.
CREATE TABLE checkins (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT                   NOT NULL,
    local_date   DATE                     NOT NULL,
    mood         VARCHAR(20)              NULL,
    support_need VARCHAR(20)              NULL,
    status       VARCHAR(20)              NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_checkins_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uk_checkins_user_date UNIQUE (user_id, local_date),
    CONSTRAINT ck_checkins_mood CHECK (mood IN ('CALM', 'OKAY', 'SO_SO', 'ANXIOUS', 'TIRED', 'OTHER')),
    CONSTRAINT ck_checkins_support_need CHECK (support_need IN ('COMFORT', 'VENT', 'SHORT_BREAK', 'SMALL_ACTION')),
    CONSTRAINT ck_checkins_status CHECK (status IN ('SUBMITTED', 'SKIPPED'))
);

CREATE TABLE checkin_stressors (
    checkin_id BIGINT      NOT NULL,
    stressor   VARCHAR(20) NOT NULL,
    CONSTRAINT pk_checkin_stressors PRIMARY KEY (checkin_id, stressor),
    CONSTRAINT fk_checkin_stressors_checkin FOREIGN KEY (checkin_id) REFERENCES checkins (id) ON DELETE CASCADE,
    CONSTRAINT ck_checkin_stressors_value
        CHECK (stressor IN ('WORK', 'FUTURE_WORRY', 'COMPARISON', 'RELATIONSHIP', 'NO_REASON', 'OTHER'))
);
