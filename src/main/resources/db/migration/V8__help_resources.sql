-- LINK의 action_value는 비워 둔다: URL을 추측해서 넣지 않는다(명세 "URL 추측 금지").
-- TODO(DECISION): 시연 전 공식 URL 확인 후 새 마이그레이션으로 action_value 갱신(A_SPEC §10)
CREATE TABLE help_resources (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    situation     VARCHAR(100) NOT NULL,
    name          VARCHAR(100) NOT NULL,
    description   VARCHAR(200) NOT NULL,
    action_type   VARCHAR(10)  NOT NULL,
    action_value  VARCHAR(200) NULL,
    display_order INT          NOT NULL,
    CONSTRAINT ck_help_resources_action_type CHECK (action_type IN ('LINK', 'TEL')),
    CONSTRAINT uk_help_resources_order UNIQUE (display_order)
);

