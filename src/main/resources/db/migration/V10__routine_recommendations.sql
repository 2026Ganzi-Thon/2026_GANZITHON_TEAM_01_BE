-- engine 실패 시 가장 최근 행을 마지막 정상 값으로 쓴다(isStale). routine_ids는 JSON 배열 문자열(ADR-004).
CREATE TABLE routine_recommendations (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT                   NOT NULL,
    local_date  DATE                     NOT NULL,
    routine_ids TEXT                     NOT NULL,
    reason      VARCHAR(500)             NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_routine_recommendations_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uk_routine_recommendations_user_date UNIQUE (user_id, local_date)
);
