-- 루틴 실행 기록(A_SPEC §9·§14). 사용자·루틴·날짜(KST)당 1행 — 중복 완료해도 기록이 늘지 않는다(멱등).
-- COMPLETED는 최종 상태다. 루틴 완료는 피로 점수·단계를 바꾸지 않는다.
-- 시각은 애플리케이션 Clock 값(DEFAULT 없음).
CREATE TABLE routine_sessions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT                   NOT NULL,
    routine_id  VARCHAR(40)              NOT NULL,
    local_date  DATE                     NOT NULL,
    status      VARCHAR(20)              NOT NULL,
    started_at  TIMESTAMP WITH TIME ZONE NULL,
    finished_at TIMESTAMP WITH TIME ZONE NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_routine_sessions_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_routine_sessions_routine FOREIGN KEY (routine_id) REFERENCES routine_catalog (routine_id),
    CONSTRAINT uk_routine_sessions_user_routine_date UNIQUE (user_id, routine_id, local_date),
    CONSTRAINT ck_routine_sessions_status CHECK (status IN ('STARTED', 'COMPLETED', 'SKIPPED'))
);

CREATE INDEX idx_routine_sessions_user_date ON routine_sessions (user_id, local_date);
