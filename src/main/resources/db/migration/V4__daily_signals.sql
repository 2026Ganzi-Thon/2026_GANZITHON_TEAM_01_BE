-- 동의(연결)한 연동 소스의 일 단위 집계값(명세 §5 저장 형태). 세부 로그(분 단위 원시 기록, 앱별·일정별 행)는 저장하지 않는다.
-- '안 보는 것'(일정 제목·내용·참석자, 위치·이동 경로, 앱 내용·메시지·검색 기록, 다른 건강 기록)을 담을 컬럼은 만들지 않는다.
-- 결측은 행이 없다(0으로 채우지 않는다). hour_bucket은 시간대별 지표(SCREEN_TIME_MINUTES)만 0~23, 나머지는 NULL.
-- 키 유니크는 NULLS NOT DISTINCT(PostgreSQL 15+): 기본 UNIQUE는 NULL끼리 다르게 보아 hour_bucket NULL 행이 중복된다.
-- collected_at은 애플리케이션 Clock 값이므로 DEFAULT를 두지 않는다.
CREATE TABLE daily_signals (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT                   NOT NULL,
    local_date   DATE                     NOT NULL,
    source       VARCHAR(40)              NOT NULL,
    metric_key   VARCHAR(40)              NOT NULL,
    value        NUMERIC(12, 2)           NULL,
    value_at     TIMESTAMP WITH TIME ZONE NULL,
    unit         VARCHAR(20)              NULL,
    hour_bucket  SMALLINT                 NULL,
    provider     VARCHAR(20)              NOT NULL,
    collected_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_daily_signals_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uk_daily_signals_key
        UNIQUE NULLS NOT DISTINCT (user_id, local_date, source, metric_key, hour_bucket)
);

CREATE INDEX idx_daily_signals_user_date ON daily_signals (user_id, local_date);
